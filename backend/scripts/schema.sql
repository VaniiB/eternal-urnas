IF OBJECT_ID(N'Products', N'U') IS NULL
CREATE TABLE Products (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  Slug NVARCHAR(80) NOT NULL UNIQUE,
  Name NVARCHAR(120) NOT NULL,
  Category NVARCHAR(60) NOT NULL,
  PriceCents INT NOT NULL,
  Blurb NVARCHAR(600) NOT NULL,
  Material NVARCHAR(200) NOT NULL,
  Seed NVARCHAR(200) NOT NULL,
  Stock INT NOT NULL CONSTRAINT DF_Products_Stock DEFAULT 0,
  Kind NVARCHAR(20) NOT NULL CONSTRAINT DF_Products_Kind DEFAULT N'urna',
  Active BIT NOT NULL CONSTRAINT DF_Products_Active DEFAULT 1,
  CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_Products_Created DEFAULT SYSUTCDATETIME()
);
GO

IF COL_LENGTH(N'Products', N'Kind') IS NULL
ALTER TABLE Products ADD Kind NVARCHAR(20) NOT NULL CONSTRAINT DF_Products_Kind DEFAULT N'urna';
GO

IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = N'CK_Products_Kind')
ALTER TABLE Products ADD CONSTRAINT CK_Products_Kind CHECK (Kind IN (N'urna', N'planta'));
GO

IF OBJECT_ID(N'Users', N'U') IS NULL
CREATE TABLE Users (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  Email NVARCHAR(200) NOT NULL UNIQUE,
  PasswordHash NVARCHAR(200) NOT NULL,
  FullName NVARCHAR(200) NOT NULL,
  Role NVARCHAR(20) NOT NULL CONSTRAINT CK_Users_Role CHECK (Role IN (N'admin', N'customer')),
  CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_Users_Created DEFAULT SYSUTCDATETIME()
);
GO

IF OBJECT_ID(N'Orders', N'U') IS NULL
CREATE TABLE Orders (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  Code NVARCHAR(20) NOT NULL UNIQUE,
  CustomerName NVARCHAR(200) NOT NULL,
  CustomerEmail NVARCHAR(200) NOT NULL,
  CustomerPhone NVARCHAR(40) NOT NULL,
  CeremonyNote NVARCHAR(800) NULL,
  Status NVARCHAR(30) NOT NULL,
  TotalCents INT NOT NULL,
  MpPreferenceId NVARCHAR(80) NULL,
  MpPaymentId NVARCHAR(80) NULL,
  StockReturned BIT NOT NULL CONSTRAINT DF_Orders_Stock DEFAULT 0,
  CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_Orders_Created DEFAULT SYSUTCDATETIME()
);
GO

IF OBJECT_ID(N'OrderItems', N'U') IS NULL
CREATE TABLE OrderItems (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  OrderId INT NOT NULL REFERENCES Orders(Id),
  ProductId INT NOT NULL REFERENCES Products(Id),
  ProductName NVARCHAR(120) NOT NULL,
  UnitPriceCents INT NOT NULL,
  Quantity INT NOT NULL
);
GO

IF OBJECT_ID(N'Settings', N'U') IS NULL
CREATE TABLE Settings (
  [Key] NVARCHAR(60) PRIMARY KEY,
  Value NVARCHAR(200) NOT NULL
);
GO
